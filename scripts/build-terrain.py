"""Build an exact, grid-subdivided terrain mesh from the historical polygons.

Requires ezdxf (Mapbox earcut implementation) only when regenerating the mesh;
the game itself has no runtime dependency on Python. Each polygon, including
holes, is triangulated and each triangle is clipped to a grid cell. This keeps
shared terrain vertices on the same grid and the outer edge on the source coast.
"""
import json, math, sys
from pathlib import Path
from ezdxf.math import Vec2
from ezdxf.math._mapbox_earcut import earcut

root = Path(__file__).resolve().parent.parent
target = Path(sys.argv[1]).resolve() if len(sys.argv)>1 else root/'dist'
raw = (target/'map-data.js').read_text()
regions = json.loads(raw.split('=', 1)[1].strip().rstrip(';'))
step = 10 if len(sys.argv)>1 else 4

def area(ring):
    return abs(sum(a[0]*b[1]-b[0]*a[1] for a,b in zip(ring,ring[1:]+ring[:1]))/2)

def cut(poly, axis, value, keep_above):
    if not poly: return []
    result=[]
    old=poly[-1]
    old_in = old[axis] >= value-1e-9 if keep_above else old[axis] <= value+1e-9
    for new in poly:
        new_in = new[axis] >= value-1e-9 if keep_above else new[axis] <= value+1e-9
        if old_in != new_in:
            t = (value-old[axis])/(new[axis]-old[axis])
            result.append((old[0]+t*(new[0]-old[0]),old[1]+t*(new[1]-old[1])))
        if new_in: result.append(new)
        old,old_in = new,new_in
    return result

def clip_triangle(tri,x,z):
    poly=tri
    for axis,val,up in ((0,x,True),(0,x+step,False),(1,z,True),(1,z+step,False)):
        poly=cut(poly,axis,val,up)
        if len(poly)<3:return []
    return poly

meshes=[]
for region in regions:
    vertices=[]; indices=[]; seen={}; expected=0; source_area=0; clipped_area=0
    def index(p):
        key=(round(p[0],5),round(p[1],5))
        if key not in seen:
            seen[key]=len(vertices)//2;vertices.extend(key)
        return seen[key]
    for poly in region['polys']:
        rings=[[Vec2(*p) for p in ring] for ring in poly]
        expected+=area(poly[0])-sum(area(ring) for ring in poly[1:])
        triangles=earcut(rings[0],rings[1:])
        for triangle in triangles:
            t=[(p.x,p.y) for p in triangle]
            source_area+=area(t)
            xmin=math.floor(min(p[0] for p in t)/step)*step;xmax=math.floor(max(p[0] for p in t)/step)*step
            zmin=math.floor(min(p[1] for p in t)/step)*step;zmax=math.floor(max(p[1] for p in t)/step)*step
            for z in range(zmin,zmax+step,step):
                for x in range(xmin,xmax+step,step):
                    clipped=clip_triangle(t,x,z)
                    if not clipped: continue
                    for i in range(1,len(clipped)-1):
                        part=[clipped[0],clipped[i],clipped[i+1]]
                        a=area(part)
                        if a<1e-8:continue
                        ids=[index(p) for p in part]
                        if len(set(ids))<3:continue
                        indices.extend(ids);clipped_area+=a
    if abs(source_area-expected)>max(.05,expected*1e-5):
        raise ValueError(f"{region['name']}: triangulation area mismatch {source_area} vs {expected}")
    if abs(clipped_area-source_area)>max(.05,expected*1e-5):
        raise ValueError(f"{region['name']}: grid clipping area mismatch {clipped_area} vs {source_area}")
    meshes.append({'id':region['id'],'v':vertices,'i':indices})
    print(region['name'],len(vertices)//2,len(indices)//3)
output='// Generated by scripts/build-terrain.py; polygons clipped exactly to the source boundaries.\nconst TERRAIN_MESH='+json.dumps(meshes,separators=(',',':'),ensure_ascii=False)+';\n'
(target/'terrain-mesh.js').write_text(output)
print('Saved',sum(len(m['i'])//3 for m in meshes),'triangles;',len(output),'bytes')
